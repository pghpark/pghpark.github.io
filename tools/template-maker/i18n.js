// v2: a choice saved before Chinese became the default is ignored once.
const STORAGE_KEY = 'template-maker:lang-v2';

function detectLang() {
  const fromUrl = new URLSearchParams(location.search).get('lang');
  if (fromUrl && LANGS[fromUrl]) return fromUrl;
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && LANGS[saved]) return saved;
  } catch { /* storage blocked */ }
  return 'zh'; // Traditional Chinese unless chosen otherwise (EN | 繁中 is remembered)
}

let current = detectLang();
export const getLang = () => current;

/** Translate a key, filling {placeholders} from vars. Unknown keys fall back to English, then the key. */
export function t(key, vars = {}) {
  const s = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
}

/** Translate everything marked with data-i18n* attributes under root. */
export function applyI18n(root = document) {
  document.documentElement.lang = LANGS[current].htmlLang;
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-aria-label]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel)));
}

export function setLang(lang) {
  if (!LANGS[lang]) return;
  current = lang;
  try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* storage blocked */ }
  // Keep a ?lang= link in the address bar in step with the choice.
  const url = new URL(location.href);
  if (url.searchParams.has('lang')) {
    url.searchParams.set('lang', lang);
    history.replaceState(null, '', url);
  }
  applyI18n();
  document.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
}
